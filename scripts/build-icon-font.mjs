/**
 * Generates `src/styles/phosphor-subset.css` from the installed
 * `@phosphor-icons/web` package.
 *
 * The site used to pull the full Phosphor stylesheet from unpkg.com — a
 * render-blocking request to a third-party origin, for ~1,500 icons of which we
 * use about 34. This cuts the font to the glyphs actually referenced in the
 * source and inlines it as a data URI, so the icons cost no request at all.
 *
 * Run `npm run build:icons` after adding or removing a `ph-*` class. The
 * generated CSS is committed, so a normal build needs neither this script nor
 * its dependencies.
 */
import { readdir, readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";
import subsetFont from "subset-font";

const PKG = "node_modules/@phosphor-icons/web/src/regular";
const SRC = "src";
const OUT = "src/styles/phosphor-subset.css";

/** Every `ph-*` class name appearing anywhere in the source. */
async function usedIconNames() {
  const names = new Set();
  async function walk(dir) {
    for (const entry of await readdir(dir, { withFileTypes: true })) {
      const path = join(dir, entry.name);
      if (entry.isDirectory()) await walk(path);
      else if (/\.(tsx?|css)$/.test(entry.name)) {
        const text = await readFile(path, "utf8");
        for (const [, name] of text.matchAll(/\bph-([a-z0-9-]+)\b/g)) names.add(name);
      }
    }
  }
  await walk(SRC);
  return names;
}

const used = await usedIconNames();
const css = await readFile(join(PKG, "style.css"), "utf8");

/* `.ph.ph-name:before { content: "\e123"; }` */
const rules = [...css.matchAll(/\.ph\.ph-([a-z0-9-]+):before\s*\{\s*content:\s*"\\([0-9a-f]+)";/g)];
const byName = new Map(rules.map(([, name, hex]) => [name, hex]));

const wanted = [];
const missing = [];
for (const name of [...used].sort()) {
  const hex = byName.get(name);
  if (hex) wanted.push({ name, hex });
  else missing.push(name);
}

if (missing.length) {
  // A name in the source with no glyph would render as a blank box.
  console.error(`No such Phosphor icon: ${missing.join(", ")}`);
  process.exit(1);
}

const text = wanted.map((i) => String.fromCodePoint(parseInt(i.hex, 16))).join("");
const full = await readFile(join(PKG, "Phosphor.woff2"));
const subset = await subsetFont(full, text, { targetFormat: "woff2" });

/* The `.ph` block is copied from the upstream stylesheet, minus the ligature
   and SVG-fallback lines the icon classes here do not use. */
const out = `/* GENERATED by scripts/build-icon-font.mjs — do not edit by hand.
   ${wanted.length} of Phosphor's icons, the ones this site actually uses,
   subset from @phosphor-icons/web and inlined so they cost no request.
   Regenerate with: npm run build:icons */

@font-face {
  font-family: "Phosphor";
  src: url("data:font/woff2;base64,${subset.toString("base64")}") format("woff2");
  font-weight: normal;
  font-style: normal;
  font-display: block;
}

.ph {
  font-family: "Phosphor" !important;
  font-style: normal;
  font-weight: normal;
  font-variant: normal;
  text-transform: none;
  line-height: 1;
  speak: never;
  display: inline-block;
  -webkit-font-smoothing: antialiased;
  -moz-osx-font-smoothing: grayscale;
}

${wanted.map((i) => `.ph.ph-${i.name}:before {\n  content: "\\${i.hex}";\n}`).join("\n\n")}
`;

await writeFile(OUT, out);
console.log(
  `${OUT}: ${wanted.length} icons, font ${(subset.length / 1024).toFixed(1)}kB ` +
    `(down from ${(full.length / 1024).toFixed(1)}kB)`,
);
